-- Optional local-model enrichment of job descriptions (ADR 0005).
--
-- jobs.description_hash identifies the text the model read (surrounding
-- whitespace ignored). It is a plain hash so the migration stays fast on a large
-- catalog; collapsing inner whitespace made it take over a minute on 30,000 jobs.
-- It is derived data, never written by the application.
-- convert_to is only STABLE in general, but with a constant UTF8 target it is
-- deterministic, so the wrapper is declared IMMUTABLE for the generated column.
CREATE FUNCTION rolescout_description_hash(description TEXT) RETURNS CHAR(64) AS $$
    SELECT encode(sha256(convert_to(btrim(description, E' \t\r\n'), 'UTF8')), 'hex')::char(64)
$$ LANGUAGE sql IMMUTABLE;

ALTER TABLE jobs ADD COLUMN description_hash CHAR(64) GENERATED ALWAYS AS (rolescout_description_hash(description)) STORED;

-- One row per job and cache key. A description that was already read for
-- another job is copied (same hash, model, prompt and schema version), so the
-- model never reads the same text twice. Failures back off in next_attempt_at.
CREATE TABLE job_enrichments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id UUID NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    description_hash CHAR(64) NOT NULL,
    model TEXT NOT NULL,
    prompt_version INTEGER NOT NULL,
    schema_version INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('ok', 'failed')),
    data JSONB,
    error TEXT,
    prompt_tokens INTEGER NOT NULL DEFAULT 0,
    completion_tokens INTEGER NOT NULL DEFAULT 0,
    latency_ms INTEGER NOT NULL DEFAULT 0,
    attempts INTEGER NOT NULL DEFAULT 1 CHECK (attempts > 0),
    next_attempt_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((status = 'ok') = (data IS NOT NULL)),
    UNIQUE (job_id, description_hash, model, prompt_version, schema_version)
);
CREATE INDEX job_enrichments_job_idx ON job_enrichments (job_id, created_at DESC);
CREATE INDEX job_enrichments_hash_idx ON job_enrichments (description_hash, model, prompt_version, schema_version)
    WHERE status = 'ok';

-- One short, workspace-private explanation per match (generated by the model
-- from facts already stored, so it can be cached by the same text hash).
CREATE TABLE match_explanations (
    workspace_id UUID NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    profile_id UUID NOT NULL REFERENCES research_profiles (id) ON DELETE CASCADE,
    job_id UUID NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    description_hash CHAR(64) NOT NULL,
    model TEXT NOT NULL,
    prompt_version INTEGER NOT NULL,
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (workspace_id, profile_id, job_id, description_hash, model, prompt_version),
    FOREIGN KEY (workspace_id, profile_id) REFERENCES research_profiles (workspace_id, id) ON DELETE CASCADE
);
