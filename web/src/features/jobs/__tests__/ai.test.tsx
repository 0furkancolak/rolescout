import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, describe, expect, it, vi } from "vitest";
import { Providers } from "../../../app/Providers";
import { createQueryClient } from "../../../app/queryClient";
import { makeJob, makeProfile, makeWorkspaceJob, mockApi, renderApp, signedIn, WS } from "../../../test/utils";
import { AiBadge } from "../AiBadge";

afterEach(() => vi.unstubAllGlobals());

const base = `/workspaces/${WS}`;
const facets = { posted: {}, arrangement: {}, seniority: {}, country: {}, technologies: [], companies: [] };

describe("AiBadge", () => {
  it("is a small pill with an accessible name that names the model", () => {
    render(
      <Providers client={createQueryClient()} locale="en">
        <AiBadge model="qwen3:4b-instruct-2507-q4_K_M" />
      </Providers>,
    );
    const badge = screen.getByLabelText("Generated by an AI model: qwen3:4b-instruct-2507-q4_K_M");
    expect(badge).toHaveTextContent("AI");
    expect(badge).toHaveAttribute("title", "qwen3:4b-instruct-2507-q4_K_M");
  });
});

function browse(job: ReturnType<typeof makeWorkspaceJob>) {
  return mockApi({
    ...signedIn(),
    [`GET ${base}/research-profiles`]: { body: { data: [makeProfile()] } },
    [`GET ${base}/jobs/facets`]: { body: { data: facets } },
    [`GET ${base}/jobs`]: { body: { data: [job], next_cursor: null } },
    [`GET /jobs/${job.id}`]: { body: { data: { ...makeJob(1), listings: [] } } },
    [`GET ${base}/jobs/${job.id}/summary/stream`]: () => ({
      sse: job.ai?.summary
        ? `event: delta\ndata: ${JSON.stringify({ text: job.ai.summary.slice(0, 5) })}\n\nevent: delta\ndata: ${JSON.stringify({ text: job.ai.summary.slice(5) })}\n\nevent: done\ndata: ${JSON.stringify({ summary: job.ai.summary })}\n\n`
        : "event: unavailable\ndata: {}\n\n",
    }),
  });
}

describe("job detail with AI fields", () => {
  it("shows the summary, salary, remote policy and explanation with badges and a caption", async () => {
    browse(
      makeWorkspaceJob(1, {
        title: "Go Engineer",
        match: { score: 91, new: false, reasons: [{ code: "remote" }], explanation: "A remote Go role that fits your search." },
        ai: {
          model: "qwen3:4b", summary: "Build Go services for payments.", remote_policy: "Remote within the EU",
          salary: { min: 90000, max: 110000, currency: "EUR", period: "year" }, fields: ["seniority"], extra_technologies: ["rust"],
        },
      }),
    );
    renderApp(`/jobs?job=${makeJob(1).id}`);
    const pane = await screen.findByRole("region", { name: "Go Engineer" });
    // The summary comes from the model in the interface language.
    expect(await within(pane).findByText("Build Go services for payments.")).toBeInTheDocument();
    expect(within(pane).getAllByLabelText(/Generated by an AI model/).length).toBeGreaterThan(0);
    expect(within(pane).getByText("Remote within the EU")).toBeInTheDocument();
    expect(within(pane).getByText(/90,000/)).toBeInTheDocument();
    expect(within(pane).getByText(/110,000/)).toBeInTheDocument();
    expect(within(pane).getByText("A remote Go role that fits your search.")).toBeInTheDocument();
    expect(within(pane).getByText("rust")).toBeInTheDocument();
    expect(within(pane).getByText("Generated by an AI model; may be wrong.")).toBeInTheDocument();
  });

  it("marks the technologies the person lacks in red and the ones they have in green", async () => {
    browse(
      makeWorkspaceJob(1, {
        title: "Go Engineer",
        technologies: ["go", "php", "docker"],
        match: { score: 80, new: false, reasons: [{ code: "tech", params: { matched: "2", total: "3" } }], explanation: null },
        tech_fit: { matched: ["go", "docker"], missing: ["php"], excluded: ["php"], from_cv: true },
      }),
    );
    renderApp(`/jobs?job=${makeJob(1).id}`);
    const pane = await screen.findByRole("region", { name: "Go Engineer" });
    expect(within(pane).getByText(/2 of 3 technologies match you/)).toBeInTheDocument();
    expect(within(pane).getByText("Compared with your profile and CV", { exact: false })).toBeInTheDocument();
    const list = within(pane).getByRole("list", { name: "Technologies" });
    expect(within(list).getByText("php").closest("li")).toHaveClass("bg-danger-soft");
    expect(within(list).getByText("You excluded this")).toBeInTheDocument();
    expect(within(list).getByText("go").closest("li")).toHaveClass("bg-sage");
    expect(within(list).getAllByText("You have this", { selector: ".sr-only" })).toHaveLength(2);
  });

  it("hides every AI section when the model has not read the job", async () => {
    browse(makeWorkspaceJob(1, { title: "Plain Engineer", match: { score: 80, new: false, reasons: [{ code: "remote" }] } }));
    renderApp(`/jobs?job=${makeJob(1).id}`);
    const pane = await screen.findByRole("region", { name: "Plain Engineer" });
    expect(within(pane).queryByText("AI")).toBeNull();
    expect(within(pane).queryByText(/may be wrong/)).toBeNull();
    // "Summarising…" shows until the server says the model has nothing.
    await vi.waitFor(() => expect(within(pane).queryByText("Summary")).toBeNull());
  });

  it("marks a value the model filled in the facts grid", async () => {
    browse(makeWorkspaceJob(1, { title: "Gap Engineer", seniority: "senior", ai: {
      model: "qwen3:4b", summary: null, remote_policy: null, salary: null, fields: ["seniority"], extra_technologies: [],
    } }));
    renderApp(`/jobs?job=${makeJob(1).id}`);
    const pane = await screen.findByRole("region", { name: "Gap Engineer" });
    // A value the model supplied is tinted and the caption says so.
    expect(within(pane).getByText("Senior")).toBeInTheDocument();
    expect(within(pane).getByText(/may be wrong/)).toBeInTheDocument();
  });

  it("generates the AI explanation of a low-scoring match on a click", async () => {
    const job = makeWorkspaceJob(1, { title: "Weak Engineer", match: { score: 22, new: false, reasons: [{ code: "remote" }] } });
    const api = mockApi({
      ...signedIn(),
      [`GET ${base}/research-profiles`]: { body: { data: [makeProfile()] } },
      [`GET ${base}/jobs/facets`]: { body: { data: facets } },
      [`GET ${base}/jobs`]: { body: { data: [job], next_cursor: null } },
      [`GET /jobs/${job.id}`]: { body: { data: { ...makeJob(1), listings: [] } } },
      [`GET ${base}/jobs/${job.id}/summary/stream`]: { sse: "event: unavailable\ndata: {}\n\n" },
      [`POST ${base}/jobs/${job.id}/analyze`]: {
        body: { data: { explanation: "A remote role, but few of your technologies appear.", ai: null } },
      },
    });
    renderApp(`/jobs?job=${job.id}`);
    const pane = await screen.findByRole("region", { name: "Weak Engineer" });
    await userEvent.click(within(pane).getByText("Why it matches"));
    await userEvent.click(within(pane).getByRole("button", { name: "Generate AI explanation" }));
    expect(await within(pane).findByText("A remote role, but few of your technologies appear.")).toBeInTheDocument();
    const call = api.calls.find((c) => c.method === "POST" && c.path.endsWith("/analyze"));
    expect(call?.search.get("profile")).toBe(makeProfile().id);
    expect(call?.search.get("lang")).toBe("en");
    // Once there is text the button goes away.
    expect(within(pane).queryByRole("button", { name: "Generate AI explanation" })).toBeNull();
  });

  it("says why generating failed", async () => {
    const job = makeWorkspaceJob(1, { title: "Weak Engineer", match: { score: 22, new: false, reasons: [{ code: "remote" }] } });
    mockApi({
      ...signedIn(),
      [`GET ${base}/research-profiles`]: { body: { data: [makeProfile()] } },
      [`GET ${base}/jobs/facets`]: { body: { data: facets } },
      [`GET ${base}/jobs`]: { body: { data: [job], next_cursor: null } },
      [`GET /jobs/${job.id}`]: { body: { data: { ...makeJob(1), listings: [] } } },
      [`GET ${base}/jobs/${job.id}/summary/stream`]: { sse: "event: unavailable\ndata: {}\n\n" },
      [`POST ${base}/jobs/${job.id}/analyze`]: { status: 412, body: { error: { code: "ai_disabled", message: "off" } } },
    });
    renderApp(`/jobs?job=${job.id}`);
    const pane = await screen.findByRole("region", { name: "Weak Engineer" });
    await userEvent.click(within(pane).getByText("Why it matches"));
    await userEvent.click(within(pane).getByRole("button", { name: "Generate AI explanation" }));
    expect(await within(pane).findByRole("alert")).toHaveTextContent("AI is switched off");
  });

  it("offers no button once an explanation exists", async () => {
    browse(makeWorkspaceJob(1, {
      title: "Strong Engineer",
      match: { score: 90, new: false, reasons: [{ code: "remote" }], explanation: "Fits well." },
    }));
    renderApp(`/jobs?job=${makeJob(1).id}`);
    const pane = await screen.findByRole("region", { name: "Strong Engineer" });
    expect(within(pane).queryByRole("button", { name: "Generate AI explanation" })).toBeNull();
  });
});
